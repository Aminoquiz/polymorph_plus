package com.illusivesoulworks.polymorph.mixin.integration.bf_blockpack;

import com.illusivesoulworks.polymorph.api.PolymorphApi;
import java.util.Optional;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.inventory.AbstractContainerMenu;
import net.minecraft.world.inventory.CraftingContainer;
import net.minecraft.world.inventory.ResultContainer;
import net.minecraft.world.item.crafting.CraftingInput;
import net.minecraft.world.item.crafting.CraftingRecipe;
import net.minecraft.world.item.crafting.RecipeHolder;
import net.minecraft.world.item.crafting.RecipeInput;
import net.minecraft.world.item.crafting.RecipeManager;
import net.minecraft.world.item.crafting.RecipeType;
import net.minecraft.world.level.Level;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Coerce;
import org.spongepowered.asm.mixin.injection.Redirect;

@SuppressWarnings("unused")
@Mixin(targets = "com.blockfactory.blockpack.menu.WorkbenchMenu", remap = false)
public class MixinWorkbenchMenu {

  @Redirect(
      method = "updateResult(Lcom/blockfactory/blockpack/menu/WorkbenchMenu;Lnet/minecraft/world/level/Level;Lnet/minecraft/world/entity/player/Player;Lnet/minecraft/world/inventory/CraftingContainer;Lnet/minecraft/world/inventory/ResultContainer;)V",
      at = @At(
          value = "INVOKE",
          target = "Lnet/minecraft/world/item/crafting/RecipeManager;getRecipeFor(Lnet/minecraft/world/item/crafting/RecipeType;Lnet/minecraft/world/item/crafting/RecipeInput;Lnet/minecraft/world/level/Level;)Ljava/util/Optional;"),
      require = 1)
  private static Optional<RecipeHolder<CraftingRecipe>> polymorph$getRecipe(
      RecipeManager recipeManager, RecipeType<CraftingRecipe> recipeType, RecipeInput recipeInput,
      Level level, @Coerce Object menu, Level unused, Player player,
      CraftingContainer craftSlots, ResultContainer resultSlots) {
    return PolymorphApi.getInstance().getRecipeManager()
        .getPlayerRecipe((AbstractContainerMenu) menu, recipeType, (CraftingInput) recipeInput,
            level, player);
  }
}